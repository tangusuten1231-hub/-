/** その月のアイデア（北半球の月で指定） */
export function ideasFor(northMonth) {
  return SEASON_IDEAS.filter((i) => i.months.includes(northMonth));
}

/** need 条件に合う植物 */
export function plantsForNeed(need, plants) {
  if (!need) return [];
  if (need.startsWith('group:')) { const g = need.slice(6).split(','); return plants.filter((p) => g.includes(p.group)); }
  if (need.startsWith('tag:')) return plants.filter((p) => p.tags.includes(need.slice(4)));
  if (need.startsWith('form:')) return plants.filter((p) => p.form === need.slice(5));
  return plants.filter((p) => p.uses?.includes(need));
}
