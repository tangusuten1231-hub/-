const pick = (arr, rand) => arr[Math.floor(rand() * arr.length)];

/**
 * ツピのひとこと
 * ctx: { month(北半球の月), hour, plants:[植物], blooming:[名前], harvest:[名前], tasks:[タイトル], seen:数, garden名, empty:boolean }
 */
export function tsupiLine(ctx, rand = Math.random) {
  const cands = [];
  const m = ctx.month;
  cands.push(MONTHLY_WORDS[m - 1], ...SEASON[m]);
  const h = ctx.hour ?? new Date().getHours();
  const t = h < 10 ? 'morning' : h < 16 ? 'noon' : h < 19 ? 'evening' : 'night';
  cands.push(pick(TIME[t], rand));
  cands.push(pick(TRIVIA, rand));
  if (ctx.empty) {
    cands.push('まずは「プラン」で、庭のイメージを作ってみない？', '図鑑で気になる植物を「マイ庭」に集めてみよう！', 'ベランダでも庭づくりはできるよ。プランの「ベランダ」を試してみて！');
  } else {
    if (ctx.blooming?.length) cands.push(`${pick(ctx.blooming, rand)}が見頃だね。近くで香りもかいでみて！`, `いま咲いているのは${ctx.blooming.slice(0, 3).join('・')}。どれがいちばん好き？`);
    if (ctx.harvest?.length) cands.push(`${pick(ctx.harvest, rand)}がとりどきだよ。朝のうちに収穫しよう！`);
    if (ctx.tasks?.length) cands.push(`今月は「${pick(ctx.tasks, rand)}」の時期。作業暦も見てみてね。`);
    if (ctx.seen) cands.push(`これまでに${ctx.seen}種類の生き物を見つけたね。図鑑がにぎやかになってきた！`);
    else cands.push('庭で生き物を見つけたら、図鑑の「見た！」で記録してみて。');
  }
  // 季節と庭の話題を少し多めに
  return pick(cands, rand);
}
